(hst/deftrifecta-from-schema display-is-total
  monero-store.currency/->display
  {:in [:cat [:enum :xmr :btc :usd :eur :brl] [:int {:min 0 :max 1000000000000}]]
   :out schema/NonBlank
   :rel (fn [[currency-id amount] out]
          (and (string? out)
               (if (pos? (currency/scale currency-id))
                 (re-find #"\." out)
                 (not (re-find #"\." out)))
               (or (pos? amount) (re-find #"^0" out))))
   :mutation false
   :num-tests 200})

(hst/deftrifecta-from-schema median-is-a-middle
  monero-store.promote.quote/median
  {:in [:vector {:min 1 :max 12} [:double {:min 0.01 :max 100000.0}]]
   :out [:maybe number?]
   :rel (fn [xs out]
          (and (<= (apply min xs) (double out))
               (<= (double out) (apply max xs))))
   :mutation false
   :num-tests 200})

(hst/deftrifecta-from-schema scrubbing-only-ever-removes
  monero-store.collect.analytics/scrub
  {:in [:map-of :keyword [:or :string :int :boolean]]
   :out [:map-of :keyword :any]
   :rel (fn [props out]
          (and (<= (count out) (count props))
               (empty? (filter #{:email :address :tx-hash :reference :secret :token}
                               (keys out)))))
   :mutation false
   :num-tests 200})

(def PlausibleObservation
  "A WalletObservation whose amounts a chain could actually carry.

  The production schema says `[:int {:min 0}]`, and it is right to: an amount
  is a non-negative integer of atomic units and the wallet is the authority on
  it. But a generator reading that schema literally will mint transfers of
  9.2e18 piconero each and sum them past Long/MAX — an arithmetic overflow that
  is real, and that no wallet on a chain with a 1.8e19 supply cap can produce.
  The bound belongs to the generator, not to the contract."
  [:map {:closed true}
   [:wallet/address schema/NonBlank]
   [:wallet/transfers
    [:sequential {:max 6}
     [:map {:closed true}
      [:transfer/tx-hash schema/NonBlank]
      [:transfer/amount [:int {:min 0 :max 1000000000000000}]]
      [:transfer/confirmations [:int {:min 0 :max 1000}]]
      [:transfer/locked? :boolean]
      [:transfer/double-spend? :boolean]]]]
   [:wallet/unlocked-amount {:optional true} [:maybe [:int {:min 0 :max 1000000000000000}]]]])

;; The one output shape closed enough to mutate: hive-test corrupts the
;; Settlement schema and every corruption must be caught, which is what proves
;; the schema is a specification rather than a description.
(hst/deftrifecta-from-schema settlement-never-credits-a-double-spend
  monero-store.payments.chain/settlement-of
  {:in [:cat :keyword PlausibleObservation [:int {:min 0 :max 1000000000}]]
   :out schema/Settlement
   :rel (fn [[provider-id observation expected] out]
          (let [honest (remove :transfer/double-spend? (:wallet/transfers observation))]
            (and (= provider-id (:settlement/provider out))
                 (= expected (:settlement/expected-amount out))
                 (<= (:settlement/paid-amount out)
                     (reduce + 0 (map :transfer/amount honest))))))
   :mutation true
   :num-tests 100})

(deftest a-forbidden-key-never-survives-scrubbing
  (testing "the property above generates keys at random; this states the ones that matter"
    (doseq [k [:email :customer-id :address :pay-to :external-ref :reference :tx-hash :secret :token]]
      (is (= {} (analytics/scrub {k "sensitive"})) (str k " reached an analytics sink")))))
