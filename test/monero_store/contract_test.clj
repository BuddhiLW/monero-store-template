(ns monero-store.contract-test
  "The contract spine itself: that every function has one, that they are
  ENFORCED while the suite runs, and that the schemas have teeth.

  Loading this namespace instruments the whole store. Every other test in the
  suite therefore runs against instrumented functions, so a schema that lies
  about its own function fails here rather than being decoration."
  (:require [clojure.test :refer [deftest is testing]]
            [hive-schemas.test :as hst]
            [malli.core :as m]
            [malli.instrument :as mi]
            [monero-store.collect.analytics :as analytics]
            [monero-store.currency :as currency]
            [monero-store.payments.chain]
            [monero-store.promote.quote :as quote]
            [monero-store.schema :as schema]))

(mi/instrument!)

;; ---------------------------------------------------------------------------
;; coverage

(def store-namespaces
  "Every namespace of the store itself.

  `monero-store.adt` is excluded: its functions are generated by `defadt` from
  the sum declaration, so there is no form to attach a contract to and the
  generated malli schema already describes the values."
  (->> (all-ns)
       (map ns-name)
       (filter #(re-find #"^monero-store\." (str %)))
       (remove #(re-find #"-test$" (str %)))
       (remove #{'monero-store.adt 'monero-store.support})
       sort))

(defn- contracted-fns
  "[contracted uncontracted] var names in `ns-sym`.

  A protocol method is not a function this namespace defines — it dispatches to
  whatever implements it — so it carries no contract of its own."
  [ns-sym]
  (let [declared (set (keys (get (m/function-schemas) ns-sym)))
        candidates (->> (ns-interns ns-sym)
                        (filter (fn [[_ v]]
                                  (let [meta' (meta v)]
                                    (and (fn? @v)
                                         (not (:macro meta'))
                                         (not (:protocol meta'))))))
                        (map key)
                        set)]
    [(sort (filter declared candidates))
     (sort (remove declared candidates))]))

(deftest every-function-in-the-store-declares-its-contract
  (let [missing (into {}
                      (keep (fn [ns-sym]
                              (let [[_ uncontracted] (contracted-fns ns-sym)]
                                (when (seq uncontracted) [ns-sym (vec uncontracted)]))))
                      store-namespaces)]
    (testing "a new function without an m/=> is a hole in the spine, so it fails here"
      (is (= {} missing)))
    (testing "and the spine is not empty, which is the failure this guard could hide"
      (is (< 100 (reduce + (map (comp count first contracted-fns) store-namespaces)))))))

